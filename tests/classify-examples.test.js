var KNOWN_MISSES = {
  "保険の請求書類を書く": "shorui",  // 「請求書」(支払い・お金)が長い語として先に当たる
  "明日の服を準備": "mijitaku"       // 「服」だけでは片付け・買い物とも取れるので、語を足していない
};

var total = 0, ok = 0, misses = [], known = [];
Object.keys(EXAMPLES).forEach(function (id) {
  EXAMPLES[id].forEach(function (text) {
    total++;
    var r = C.classify(text);
    if (r.id === id) ok++;
    else if (KNOWN_MISSES[text] === id) known.push("「" + text + "」→ " + r.id + " 期待: " + id);
    else misses.push("「" + text + "」→ " + r.id + " 期待: " + id + "  当たった語: " + r.matched.join(",") + "  候補: " + JSON.stringify(r.candidates));
  });
});
var rate = Math.round(ok * 1000 / total) / 10;
console.log("分類の例: " + ok + " / " + total + " 件が期待どおり(正解率 " + rate + "%)");
(argv.indexOf("--all") !== -1 ? misses : misses.slice(0, 20)).forEach(function (m) { console.log("  NG  " + m); });
known.forEach(function (m) { console.log("  既知 " + m); });

