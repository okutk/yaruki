  var DEFS = { box: BOX, final: FINAL };

  /* ── 組み立て ──────────────────────────────── */
  function parseKinds(spec) {
    var all = false, only = {}, not = {};
    spec.split(/\s+/).forEach(function (k) {
      if (!k) return;
      if (k === "*") all = true;
      else if (k.charAt(0) === "-") not[k.slice(1)] = true;
      else only[k] = true;
    });
    return function (kind) { return !not[kind] && (all || !!only[kind]); };
  }

  // 「t1.5 m1 e2 w1」→ { t, m, e, w }
  function parseSize(spec) {
    var size = { t: 0, m: 0, e: 0, w: 0 };
    (spec || "").split(/\s+/).forEach(function (tok) {
      var m = /^([tmew])(\d+(?:\.\d+)?)$/.exec(tok);
      if (m) size[m[1]] = +m[2];
    });
    return size;
  }

  // 印「h seq w0-1 m0.5」→ { place, seq, span, wMin, wMax, add }
  function parseMarks(spec) {
    var out = { place: "a", seq: false, span: false, wMin: 0, wMax: 3, add: parseSize(spec) };
    (spec || "").split(/\s+/).forEach(function (tok) {
      if (tok === "h" || tok === "o") out.place = tok;
      else if (tok === "seq") out.seq = true;
      else if (tok === "span") out.span = true;
      else {
        var m = /^w(\d+)-(\d+)$/.exec(tok);
        if (m) { out.wMin = +m[1]; out.wMax = +m[2]; out.add.w = 0; }
      }
    });
    return out;
  }

  function parseTwists(list) {
    return (list || []).map(function (s) {
      var p = s.split("|");
      var r = p[2].split("-");
      var marks = parseMarks(p[3]);
      marks.text = p[0];
      marks.fits = parseKinds(p[1]);
      marks.min = +r[0];
      marks.max = +r[1];
      return marks;
    });
  }

  function parseWhens(list) {
    return (list || []).map(function (s) {
      var p = s.split("|");
      var r = p[2].split("-");
      var marks = parseMarks(p[4]);
      marks.text = p[0];
      marks.fits = parseKinds(p[1]);
      marks.min = +r[0];
      marks.max = +r[1];
      marks.w = +p[3];
      return marks;
    });
  }

  // 文ごとに「どの CONFLICTS グループの言葉を含むか」をビットで覚えておき、AND で判定する(スマホでも速い)
  var maskCache = {};
  function maskOf(text) {
    if (maskCache[text]) return maskCache[text];
    var m = [];
    for (var i = 0; i < CONFLICTS.length; i++) {
      var g = CONFLICTS[i];
      for (var j = 0; j < g.length; j++) {
        if (text.indexOf(g[j]) !== -1) { m[i >> 5] = (m[i >> 5] || 0) | (1 << (i & 31)); break; }
      }
    }
    return (maskCache[text] = m);
  }

  function hasAny(text, words) {
    for (var i = 0; i < words.length; i++) if (text.indexOf(words[i]) !== -1) return true;
    return false;
  }

  function conflicts(a, b) {
    var x = maskOf(a), y = maskOf(b);
    for (var i = 0; i < x.length; i++) if ((x[i] & (y[i] || 0)) !== 0) return true;
    for (var c = 0; c < CLASHES.length; c++) {
      var A = CLASHES[c][0], B = CLASHES[c][1];
      if ((hasAny(a, A) && hasAny(b, B)) || (hasAny(a, B) && hasAny(b, A))) return true;
    }
    return false;
  }

  function actsFor(def, level) {
    var out = [];
    (def.acts[level] || []).forEach(function (s) {
      var p = s.split("|");
      out.push({ kind: p[0], place: p[1], size: parseSize(p[2]), text: p[3] });
    });
    (def.scaled || []).forEach(function (s) {
      var p = s.split("|");
      p[4].split(";").forEach(function (entry) {
        var q = entry.split(":");
        if (+q[0] !== level) return;
        var size = parseSize(p[2]);
        size.t = +q[2];
        out.push({ kind: p[0], place: p[1], size: size, text: p[3].replace("{d}", q[1]) });
      });
    });
    return out;
  }

  // ひと工夫と行動のつなぎ方。
  // 「スマホを置いて」「日の当たる場所で」のように、動作や場所のまとまり(〜て・〜で・〜ながら・〜から)は読点で区切る。
  // 「目を閉じて」「こっそり」「丁寧に」のような短い言い方は、そのまま続ける。
  function joinTwist(twist, act) {
    if (!twist) return act;
    var clause = twist.length >= 9 || (twist.length >= 6 && /(?:て|で|ながら|から)$/.test(twist));
    return twist + (clause ? "、" : "") + act;
  }

  // 動作の連なりが長すぎないか。「〜してから」「〜したら」「〜て、」は2つ目から、読点は3つ目から長すぎる
  function tooLong(text) {
    var t = text.replace(/だらだら/g, "");
    var steps = (t.match(/てから|でから|たら|だら|たあとで|だあとで|[てで]、/g) || []).length;
    var commas = (t.match(/、/g) || []).length;
    return steps >= 2 || commas >= 3;
  }

  function score(size) { return size.t + size.m + size.e + size.w; }

  // 1件ぶんの組み合わせを作る。合わなければ null
  function combine(type, act, twist, when) {
    var aw = act.size.w;
    if (when) {
      // 小さいご褒美を先に延ばさない・大きいご褒美を今すぐにしない
      if (when.w < aw - 0.5 || when.w > aw + 1) return null;
      if (twist && (when.w < twist.wMin || when.w > twist.wMax)) return null;
      if (twist && twist.span && !when.span) return null;
      if (twist && twist.seq && when.seq) return null;
      if (twist && conflicts(when.text, twist.text)) return null;
    }
    var w = Math.max(aw, when ? when.w : 0, twist ? twist.wMin : 0);
    if (twist && w > twist.wMax) return null;
    var places = [act.place, twist ? twist.place : "a", when ? when.place : "a"];
    var place = places.indexOf("o") !== -1 ? "o" : places.indexOf("h") !== -1 ? "h" : "a";
    if (place === "o" && places.indexOf("h") !== -1) return null;
    var add = twist ? twist.add : { t: 0, m: 0, e: 0, w: 0 };
    var size = { t: act.size.t + add.t, m: act.size.m + add.m, e: act.size.e + add.e, w: w };
    var body = joinTwist(twist && twist.text, act.text);
    var text = when ? when.text + "、" + body : body;
    if (tooLong(text)) return null;
    return {
      text: text,
      kind: act.kind,
      act: act.text,
      place: place,
      size: size,
      base: score(act.size),
      score: score(size)
    };
  }

  // その場所で使えるか。外にいるときの全完了のご褒美は、今夜以降(w が1以上)なら家のものも使える
  function fitsPlace(type, item, place) {
    if (place === "out") return item.place !== "h" || (type === "final" && item.size.w >= 1);
    return item.place !== "o";
  }

  var fullCache = {};
  function fullPool(type, level) {
    var key = type + level;
    if (fullCache[key]) return fullCache[key];
    var def = DEFS[type];
    var inLevel = function (x) { return x.min <= level && level <= x.max; };
    var twists = parseTwists(def.twists).filter(inLevel);
    var whens = parseWhens(def.whens).filter(inLevel);
    var seen = {}, items = [];
    actsFor(def, level).forEach(function (act) {
      var tws = [null].concat(twists.filter(function (t) { return t.fits(act.kind) && !conflicts(t.text, act.text); }));
      var whs = [null].concat(whens.filter(function (w) { return w.fits(act.kind) && !conflicts(w.text, act.text); }));
      whs.forEach(function (w) {
        tws.forEach(function (t) {
          var item = combine(type, act, t, w);
          if (!item || item.text.length > MAX_LEN[type] || seen[item.text]) return;
          seen[item.text] = true;
          item.index = items.length;
          items.push(item);
        });
      });
    });
    fullCache[key] = items;
    return items;
  }

  function placeOf(opts) {
    return opts && opts.place === "out" ? "out" : "home";
  }

  // 場所で絞った組み合わせ(details)と、その文だけの配列(pool)
  var detailCache = {}, poolCache = {};
  function details(type, level, opts) {
    level = clampLevel(level);
    var place = placeOf(opts);
    var key = type + level + place;
    if (!detailCache[key]) {
      detailCache[key] = fullPool(type, level).filter(function (it) { return fitsPlace(type, it, place); });
    }
    return detailCache[key];
  }

  function pool(type, level, opts) {
    level = clampLevel(level);
    var key = type + level + placeOf(opts);
    if (!poolCache[key]) poolCache[key] = details(type, level, opts).map(function (it) { return it.text; });
    return poolCache[key];
  }

  // 部品データのハッシュ。部品を変えると値が変わり、古い履歴はリセットされる(全レベルを作らずに求められる)
  var sigCache = {};
  function signature(type) {
    if (sigCache[type]) return sigCache[type];
    var src = JSON.stringify([VERSION, MAX_LEN[type], CONFLICTS, CLASHES, DEFS[type]]);
    var h = 0x811c9dc5;
    for (var i = 0; i < src.length; i++) {
      h ^= src.charCodeAt(i);
      h = Math.imul(h, 0x01000193) >>> 0;
    }
    return (sigCache[type] = "v" + VERSION + ":" + h.toString(16));
  }

  /* ── 抽選 ────────────────────────────────────
   * hist は種類(box/final)ごとの履歴。JSON にしてそのまま保存できる。
   *   { sig: 部品の署名, used: { レベル: 16進のビット列 }, recent: [直近のID…] }
   * ID と used のビットは、場所で絞る前の並び(fullPool)の番号で数える。場所を変えても履歴は共通。
   * draw() は hist を書き換える。保存は呼び出し側で行う。 */
  function emptyHistory(type) {
    return { sig: signature(type), used: {}, recent: [] };
  }

  function checkHistory(type, hist) {
    if (!hist || typeof hist !== "object" || hist.sig !== signature(type) ||
        typeof hist.used !== "object" || !Array.isArray(hist.recent)) {
      return emptyHistory(type);
    }
    return hist;
  }

  function decodeBits(hex, n) {
    var bits = new Uint8Array(n);
    if (typeof hex !== "string") return bits;
    for (var c = 0; c < hex.length; c++) {
      var v = parseInt(hex.charAt(c), 16) || 0;
      for (var b = 0; b < 4; b++) {
        var i = c * 4 + b;
        if (i < n && (v >> b) & 1) bits[i] = 1;
      }
    }
    return bits;
  }

  function encodeBits(bits) {
    var s = "";
    for (var i = 0; i < bits.length; i += 4) {
      var v = 0;
      for (var b = 0; b < 4 && i + b < bits.length; b++) if (bits[i + b]) v |= 1 << b;
      s += v.toString(16);
    }
    return s;
  }

  function clampLevel(level) {
    level = Math.round(Number(level) || 1);
    return Math.max(1, Math.min(LEVELS, level));
  }

  // opts.place: "out" なら外で使えるものだけから引く(省略時は家・どこでも)
  function draw(type, level, hist, rng, opts) {
    rng = rng || Math.random;
    level = clampLevel(level);
    var all = fullPool(type, level), n = all.length;
    var list = details(type, level, opts);
    var used = decodeBits(hist.used[level], n);
    var recentAt = {};
    hist.recent.forEach(function (id, k) { recentAt[id] = k; });
    var base = level * ID_BASE;

    var cand = [];
    list.forEach(function (it) { if (!used[it.index] && recentAt[base + it.index] === undefined) cand.push(it.index); });
    if (!cand.length) {
      // この場所で使えるものを使い切った。その分だけ「出した」を消して、新しい周回を始める。
      list.forEach(function (it) {
        used[it.index] = 0;
        if (recentAt[base + it.index] === undefined) cand.push(it.index);
      });
    }
    if (!cand.length) {
      // 直近の履歴に全部入っている(候補がとても少ないとき)。一番前に出したものを選ぶ。
      var oldest = null;
      list.forEach(function (it) {
        if (oldest === null || recentAt[base + it.index] < recentAt[base + oldest]) oldest = it.index;
      });
      cand.push(oldest);
    }
    var pick = cand[Math.min(cand.length - 1, Math.floor(rng() * cand.length))];
    used[pick] = 1;
    hist.used[level] = encodeBits(used);
    hist.recent.push(base + pick);
    if (hist.recent.length > RECENT_LIMIT) hist.recent.splice(0, hist.recent.length - RECENT_LIMIT);
    return { id: base + pick, level: level, text: all[pick].text };
  }

  return {
    VERSION: VERSION,
    LEVELS: LEVELS,
    RECENT_LIMIT: RECENT_LIMIT,
    MAX_LEN: MAX_LEN,
    BANDS: BANDS,
    pool: pool,
    details: details,
    signature: signature,
    emptyHistory: emptyHistory,
    checkHistory: checkHistory,
    draw: draw
  };
